import { Page, Locator } from '@playwright/test';
import { baseURL } from '../../config'; // Import base URL from config

/**
 * Represents the Login Page of the application using the Page Object Model.
 * Encapsulates selectors and actions related to the login functionality.
 */
export class LoginPage {
    private readonly page: Page; // Playwright Page object
    readonly usernameInput: Locator;
    readonly passwordInput: Locator;
    readonly loginButton: Locator;
    readonly errorMessage: Locator;

    /**
     * Constructor for LoginPage.
     * @param page The Playwright Page object.
     */
    constructor(page: Page) {
        this.page = page;
        this.usernameInput = page.getByLabel('Username').or(page.locator('#username')).or(page.locator('[name="username"]'));
        this.passwordInput = page.getByLabel('Password').or(page.locator('#password')).or(page.locator('[name="password"]'));
        this.loginButton = page.getByRole('button', { name: 'Login' }).or(page.locator('input[type="submit"]'));
        this.errorMessage = page.locator('[data-testid="login-error"]').or(page.getByText('Invalid credentials.'));
    }

    /**
     * Navigates to the login page.
     */
    async navigate(): Promise<void> {
        await this.page.goto(`${baseURL}/login`);
        await this.page.waitForLoadState('domcontentloaded');
    }

    /**
     * Performs a login action with the given credentials.
     * @param username The username to enter.
     * @param password The password to enter.
     */
    async login(username: string, password: string): Promise<void> {
        await this.usernameInput.fill(username);
        await this.passwordInput.fill(password);
        await this.loginButton.click();
    }

    /**
     * Asserts that an error message is visible after a failed login attempt.
     * @param message Optional. The expected text content of the error message.
     */
    async verifyErrorMessageVisible(message?: string): Promise<void> {
        await expect(this.errorMessage).toBeVisible();
        if (message) {
            await expect(this.errorMessage).toContainText(message);
        }
    }
}

