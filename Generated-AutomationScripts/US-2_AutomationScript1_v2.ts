// playwright-framework/auth.setup.ts
import { test as setup, expect } from '@playwright/test';
import { baseURL } from '../src/config';
import { PageManager } from '../src/pages/PageManager';
import users from '../src/test-data/users.json';
import path from 'path';

// Define the path for the authentication state file
const authFile = path.join(__dirname, '..', 'playwright/.auth/user.json');

/**
 * This setup script handles the authentication process for a 'salesman' user.
 * It logs in the user and saves their authentication state (cookies, local storage, etc.)
 * to a file, which can then be reused by subsequent tests to avoid repeated logins.
 */
setup('authenticate as salesman', async ({ page }) => {
    const pageManager = new PageManager(page);
    const salesmanUser = users.salesman; // Get salesman credentials from test-data

    // 1. Navigate to the login page
    await page.goto(baseURL + '/login');
    await page.waitForLoadState('domcontentloaded'); // Ensure page is loaded

    // 2. Perform login using the LoginPage Page Object
    await test.step('Perform Salesman Login', async () => {
        await expect(pageManager.loginPage.usernameInput).toBeVisible(); // Assert login page loaded
        await pageManager.loginPage.login(salesmanUser.username, salesmanUser.password);
    });

    // 3. Wait for post-login redirection and assert success
    await test.step('Verify Post-Login State', async () => {
        // Wait for URL to change to the expected dashboard or home page after successful login
        await page.waitForURL(baseURL + '/dashboard', { waitUntil: 'networkidle' });
        // Assert a visible element indicating successful login, e.g., a welcome message or dashboard element
        await expect(page.locator('h1', { hasText: 'Dashboard' }).or(page.getByText(`Welcome, ${salesmanUser.username.split('@')[0]}`))).toBeVisible();
    });

    // 4. Save the authentication state
    // This will save cookies, local storage, and session storage to the specified file.
    await page.context().storageState({ path: authFile });
    console.log(`Authentication state saved to: ${authFile}`);
});

